CREATE TABLE IF NOT EXISTS users (
    user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(120) NOT NULL,
    email VARCHAR(180) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL
);

CREATE TABLE IF NOT EXISTS auditoriums (
    auditorium_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cinema_name VARCHAR(150) NOT NULL,
    auditorium_name VARCHAR(100) NOT NULL,
    auditorium_type VARCHAR(16) NOT NULL
        CHECK (auditorium_type IN ('IMAX', 'ORCHESTRA', 'STANDARD')),
    CONSTRAINT uq_cinema_auditorium UNIQUE (cinema_name, auditorium_name)
);

CREATE TABLE IF NOT EXISTS screen_interiors (
