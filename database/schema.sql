CREATE TABLE IF NOT EXISTS seats (
    seat_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    auditorium_id BIGINT NOT NULL,
    section_name VARCHAR(50) NOT NULL,
    row_label VARCHAR(10) NOT NULL,
    seat_number INT NOT NULL,
    category VARCHAR(16) NOT NULL CHECK (category IN ('STANDARD', 'PREMIUM', 'ACCESSIBLE')),
    base_price DECIMAL(10,2) NOT NULL,
    CONSTRAINT uq_physical_seat UNIQUE (auditorium_id, section_name, row_label, seat_number),
    FOREIGN KEY (auditorium_id) REFERENCES auditoriums(auditorium_id)
);

CREATE TABLE IF NOT EXISTS movies (
    movie_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(200) NOT NULL,
    duration_minutes INT,
    CONSTRAINT uq_movie_title UNIQUE (title)
);

CREATE TABLE IF NOT EXISTS shows (
    show_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    movie_id BIGINT NOT NULL,
    auditorium_id BIGINT NOT NULL,
    starts_at TIMESTAMP NOT NULL,
    CONSTRAINT uq_movie_auditorium_start UNIQUE (movie_id, auditorium_id, starts_at),
    FOREIGN KEY (movie_id) REFERENCES movies(movie_id),
    FOREIGN KEY (auditorium_id) REFERENCES auditoriums(auditorium_id)
);

CREATE TABLE IF NOT EXISTS bookings (
    booking_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    show_id BIGINT NOT NULL,
    booking_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    total_amount DECIMAL(10,2) NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'PENDING'
        CHECK (status IN ('PENDING', 'CONFIRMED', 'CANCELLED')),
    FOREIGN KEY (user_id) REFERENCES users(user_id),
    FOREIGN KEY (show_id) REFERENCES shows(show_id)
);

CREATE TABLE IF NOT EXISTS booking_contacts (
    booking_id BIGINT PRIMARY KEY,
    phone_e164 VARCHAR(13) NOT NULL,
    email VARCHAR(254) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (booking_id) REFERENCES bookings(booking_id) ON DELETE CASCADE
);


CREATE TABLE IF NOT EXISTS booking_seats (
    booking_seat_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id BIGINT NOT NULL,
    show_id BIGINT NOT NULL,
    seat_id BIGINT NOT NULL,
    price DECIMAL(10,2) NOT NULL,
    CONSTRAINT uq_show_seat UNIQUE (show_id, seat_id),
    CONSTRAINT uq_booking_seat UNIQUE (booking_id, seat_id),
    FOREIGN KEY (booking_id) REFERENCES bookings(booking_id),
    FOREIGN KEY (show_id) REFERENCES shows(show_id),
    FOREIGN KEY (seat_id) REFERENCES seats(seat_id)
);

CREATE TABLE IF NOT EXISTS payments (
    payment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id BIGINT NOT NULL,
    amount DECIMAL(10,2) NOT NULL,
    payment_method VARCHAR(40) NOT NULL DEFAULT 'DEMO',
    payment_status VARCHAR(16) NOT NULL DEFAULT 'PENDING'
        CHECK (payment_status IN ('PENDING', 'SUCCESS', 'FAILED')),
    CONSTRAINT uq_booking_payment UNIQUE (booking_id),
    FOREIGN KEY (booking_id) REFERENCES bookings(booking_id)
);

CREATE TABLE IF NOT EXISTS payment_qr_tokens (
    qr_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id BIGINT NOT NULL,
    token_hash CHAR(64) NOT NULL UNIQUE,
    status VARCHAR(16) NOT NULL DEFAULT 'PENDING'
        CHECK (status IN ('PENDING', 'SCANNED', 'REVOKED', 'EXPIRED')),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expires_at TIMESTAMP NOT NULL,
    scanned_at TIMESTAMP,
    FOREIGN KEY (booking_id) REFERENCES payments(booking_id) ON DELETE CASCADE
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_payment_qr_pending_booking
    ON payment_qr_tokens (booking_id)
    WHERE status = 'PENDING';
